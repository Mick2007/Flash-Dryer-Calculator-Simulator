import React, { useMemo } from 'react';
import katex from 'katex';

/**
 * Renders a LaTeX string with KaTeX, falling back to the raw source if the
 * expression will not compile.
 *
 * WHY NOT react-katex. The `react-katex` wrapper re-renders through its own
 * context and DOM-diffing layer, which is unnecessary here: every expression in
 * this app is a compile-time constant string, so a `useMemo` over the string
 * renders each one exactly once. Using KaTeX directly keeps one fewer dependency
 * and makes the failure path explicit — `throw: false` means a malformed
 * expression degrades to a visible source string instead of blanking the panel.
 *
 * WHY A FALLBACK MATTERS. `renderToString` with `throw: false` silently returns
 * the source text plus an error colour when it cannot parse. On a page whose
 * entire purpose is auditing a calculation, an unparseable equation must be
 * visible, not swallowed. A developer running this app can see the bad LaTeX
 * immediately and fix it, which is what happened to the handful of expressions
 * that needed brace grouping during the original conversion.
 */
export const Latex: React.FC<{
  tex: string;
  className?: string;
  /** Render on one line, for inline use in a sentence. */
  inline?: boolean;
}> = ({ tex, className, inline = false }) => {
  const html = useMemo(() => {
    if (!tex || !tex.trim()) return '';
    try {
      return katex.renderToString(tex, {
        displayMode: !inline,
        throwOnError: false,
        strict: false,
        trust: false,
        output: 'html',
        macros: {
          '\\dd': '\\mathrm{d}',
          '\\degC': '{}^{\\circ}\\mathrm{C}',
          '\\kgm': '\\mathrm{kg\\,m^{-3}}',
        },
      });
    } catch {
      return '';
    }
  }, [tex, inline]);

  // No LaTeX for this expression: show the source verbatim so the reader still
  // sees the formula, just unstyled.
  if (!html) {
    return (
      <span className={`font-mono text-[12px] break-words ${className ?? ''}`}>
        {tex}
        <span className="ml-2 text-[10px] uppercase tracking-wider text-oxide border border-oxide/40 px-1 py-0.5">
          latex parse failed
        </span>
      </span>
    );
  }

  return (
    <span
      className={className}
      // KaTeX output is generated by us from a compile-time constant, not by
      // user input, and `trust: false` already strips \href, \url and \includegraphics.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
};
